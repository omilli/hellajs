import fs from "node:fs";
import path from "node:path";
import { logger, projectRoot } from "./utils/index.ts";
import { extractBlocks } from "./snippets/blocks.ts";

/**
 * Compiler + validator for consumer-facing `*-best-practices` agent skills
 * (Vercel agent-skills format): every `.agents/skills/*-best-practices/` dir
 * with a `rules/` folder is validated (SKILL.md frontmatter limits,
 * metadata.json keys, the `rules/_sections.md` table, per-rule frontmatter /
 * single-H2 / fence / resolvable-Reference checks) and compiled into a
 * deterministic `AGENTS.md`: header (name, metadata, abstract), impact
 * legend, TOC (sections in `_sections.md` order, rules alphabetical within
 * section, numeric `n.m` ids), and each rule's content inlined verbatim.
 * `rules/` is the source of truth; the compiled artifact is regenerated by
 * `vp run skills-build`, never hand-edited. Idempotent by construction —
 * no timestamps, everything sorted. `vp run skills-check` imports the
 * corpus/validate/compile functions below for its freshness gate.
 */

/** One `*-best-practices` corpus dir (dirs without `rules/` are not corpus). */
export interface SkillEntry {
  /** Folder name, e.g. `core-best-practices`. */
  name: string;
  /** Absolute dir path. */
  dir: string;
  /** Whether `<dir>/rules/` exists. */
  hasRules: boolean;
}

/** A `rules/` markdown file with its provenance and raw text. */
export interface RuleSource {
  /** Absolute file path. */
  file: string;
  /** Repo-relative path, for problem messages. */
  relPath: string;
  /** Filename stem, e.g. `reactivity-derive-in-computeds`. */
  stem: string;
  /** Raw file text. */
  text: string;
}

/** One parsed `_sections.md` data row. */
export interface SectionRow {
  prefix: string;
  title: string;
  impact: string;
  description: string;
}

/** Everything read off one skill dir, unvalidated. */
export interface SkillSources {
  name: string;
  dir: string;
  skillMd: string | null;
  metadata: Record<string, unknown> | null;
  metadataError: string | null;
  sectionsText: string | null;
  ruleFiles: RuleSource[];
}

const SKILLS_DIR = path.join(projectRoot, ".agents", "skills");
const RULE_FENCE_LANGS = new Set(["ts", "tsx", "jsx"]);
const SKILL_NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const IMPACT_LEVELS = new Set(["CRITICAL", "HIGH", "MEDIUM", "LOW"]);
const RULE_FRONTMATTER_KEYS = new Set(["title", "impact", "impactDescription", "tags"]);
const IMPACT_LEGEND = [
  "| Level | Meaning |",
  "|---|---|",
  "| CRITICAL | Breaks correctness: lost reactivity, leaks, glitching, hydration mismatch, data loss |",
  "| HIGH | Measurable perf or UX degradation the library exists to prevent |",
  "| MEDIUM | Suboptimal: works but fights the library's model |",
  "| LOW | Convention or consistency |",
].join("\n");

/**
 * Lists the skill corpus: `.agents/skills/` subdirectories whose name ends
 * with `-best-practices` (dirs without a `rules/` folder are listed but not
 * corpus — the consumer filters on `hasRules`).
 * @returns Corpus dir entries in name order
 */
export function listSkills(): SkillEntry[] {
  const entries: SkillEntry[] = [];
  for (const entry of fs.readdirSync(SKILLS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory() || !entry.name.endsWith("-best-practices")) continue;
    const dir = path.join(SKILLS_DIR, entry.name);
    entries.push({
      name: entry.name,
      dir,
      hasRules: fs.existsSync(path.join(dir, "rules")),
    });
  }
  return entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/**
 * Reads one skill dir's sources. Missing optional files surface as `null`
 * fields (validation names them); nothing is judged here.
 * @param entry The corpus dir entry
 * @returns The raw sources
 */
export function loadSkill(entry: SkillEntry): SkillSources {
  const skillMdPath = path.join(entry.dir, "SKILL.md");
  const metadataPath = path.join(entry.dir, "metadata.json");
  let metadata: Record<string, unknown> | null = null;
  let metadataError: string | null = null;
  if (fs.existsSync(metadataPath)) {
    try {
      const parsed: unknown = JSON.parse(fs.readFileSync(metadataPath, "utf-8"));
      if (parsed !== null && typeof parsed === "object" && !Array.isArray(parsed)) {
        metadata = parsed as Record<string, unknown>;
      } else {
        metadataError = "metadata.json is not a JSON object";
      }
    } catch (error) {
      metadataError = `metadata.json is not valid JSON (${(error as Error).message})`;
    }
  }
  const rulesDir = path.join(entry.dir, "rules");
  const ruleFiles: RuleSource[] = [];
  if (fs.existsSync(rulesDir)) {
    for (const rule of fs.readdirSync(rulesDir, { withFileTypes: true })) {
      if (!rule.isFile() || !rule.name.endsWith(".md") || rule.name.startsWith("_")) continue;
      const file = path.join(rulesDir, rule.name);
      ruleFiles.push({
        file,
        relPath: path.relative(projectRoot, file),
        stem: rule.name.slice(0, -3),
        text: fs.readFileSync(file, "utf-8"),
      });
    }
    ruleFiles.sort((a, b) => (a.stem < b.stem ? -1 : a.stem > b.stem ? 1 : 0));
  }
  return {
    name: entry.name,
    dir: entry.dir,
    skillMd: fs.existsSync(skillMdPath) ? fs.readFileSync(skillMdPath, "utf-8") : null,
    metadata,
    metadataError,
    sectionsText: fs.existsSync(path.join(rulesDir, "_sections.md"))
      ? fs.readFileSync(path.join(rulesDir, "_sections.md"), "utf-8")
      : null,
    ruleFiles,
  };
}

/**
 * Parses simple frontmatter: `---`-fenced key/value pairs (scalar values, or
 * `>` / `|` block scalars folded to one space-joined line) followed by the
 * body. No YAML dependency — the skill format only uses these shapes.
 * @param text Raw file text
 * @returns The parsed keys and body, or null when no frontmatter block exists
 */
export function parseFrontmatter(text: string): { data: Map<string, string>; body: string } | null {
  const lines = text.split("\n");
  if (lines[0] !== "---") return null;
  const close = lines.indexOf("---", 1);
  if (close === -1) return null;
  const data = new Map<string, string>();
  let i = 1;
  while (i < close) {
    const m = lines[i]!.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (m === null) {
      i += 1;
      continue;
    }
    const key = m[1]!;
    let value = m[2]!;
    if (value === ">" || value === ">-" || value === "|" || value === "|-") {
      const parts: string[] = [];
      i += 1;
      while (i < close && (lines[i]!.startsWith(" ") || lines[i]!.startsWith("\t"))) {
        if (lines[i]!.trim()) parts.push(lines[i]!.trim());
        i += 1;
      }
      value = parts.join(" ");
    } else {
      i += 1;
    }
    data.set(key, value.trim());
  }
  return { data, body: lines.slice(close + 1).join("\n") };
}

/**
 * Splits a markdown table line into trimmed cells (leading/trailing pipes
 * dropped, trailing empty cell from a closing pipe dropped).
 * @param line The table line
 * @returns The trimmed cells
 */
function tableCells(line: string): string[] {
  const parts = line.split("|");
  parts.shift();
  if (parts.length > 0 && parts[parts.length - 1]!.trim() === "") parts.pop();
  return parts.map((c) => c.trim());
}

/**
 * Parses the `rules/_sections.md` table.
 * @param text Raw `_sections.md` text
 * @returns The data rows and an error message when the table is missing or malformed
 */
function parseSectionsTable(text: string): { rows: SectionRow[]; error: string | null } {
  const lines = text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.startsWith("|"));
  if (lines.length < 2) return { rows: [], error: "_sections.md has no markdown table" };
  const header = tableCells(lines[0]!);
  if (header.join("|") !== ["prefix", "title", "impact", "description"].join("|")) {
    return {
      rows: [],
      error: "_sections.md table header must be `| prefix | title | impact | description |`",
    };
  }
  const rows: SectionRow[] = [];
  for (const line of lines.slice(1)) {
    const cells = tableCells(line);
    if (cells.every((c) => /^:?-{3,}:?$/.test(c))) continue; // delimiter row
    if (cells.length !== 4) {
      return { rows, error: `_sections.md row has ${cells.length} cells, expected 4: \`${line}\`` };
    }
    rows.push({ prefix: cells[0]!, title: cells[1]!, impact: cells[2]!, description: cells[3]! });
  }
  if (rows.length === 0) return { rows, error: "_sections.md table has no data rows" };
  const prefixes = rows.map((r) => r.prefix);
  if (new Set(prefixes).size !== prefixes.length) {
    return { rows, error: "_sections.md prefixes are not unique" };
  }
  return { rows, error: null };
}

/**
 * Validates one skill's sources; every check the compiled artifact depends on.
 * @param sources The loaded skill sources
 * @returns Problem strings (`repo-relative path: problem`), empty when valid
 */
export function validateSkill(sources: SkillSources): string[] {
  const problems: string[] = [];
  const skillRel = path.relative(projectRoot, path.join(sources.dir, "SKILL.md"));
  if (sources.skillMd === null) {
    problems.push(`${skillRel}: missing`);
  } else {
    const fm = parseFrontmatter(sources.skillMd);
    const name = fm?.data.get("name") ?? "";
    const description = fm?.data.get("description") ?? "";
    if (name !== sources.name) {
      problems.push(`${skillRel}: frontmatter name "${name}" does not equal folder name`);
    }
    if (!SKILL_NAME_RE.test(name) || name.length > 64) {
      problems.push(`${skillRel}: name must be lowercase-hyphen and <= 64 chars`);
    }
    if (description.length === 0) {
      problems.push(`${skillRel}: description is empty`);
    }
    if (description.length > 1024) {
      problems.push(`${skillRel}: description is ${description.length} chars, max 1024`);
    }
  }

  const metadataRel = path.relative(projectRoot, path.join(sources.dir, "metadata.json"));
  if (sources.metadataError !== null) {
    problems.push(`${metadataRel}: ${sources.metadataError}`);
  } else if (sources.metadata === null) {
    problems.push(`${metadataRel}: missing`);
  } else {
    for (const key of ["version", "organization", "date", "abstract"]) {
      const value = sources.metadata[key];
      if (typeof value !== "string" || value.length === 0) {
        problems.push(`${metadataRel}: key "${key}" must be a non-empty string`);
      }
    }
  }

  const sectionsRel = path.relative(projectRoot, path.join(sources.dir, "rules", "_sections.md"));
  if (sources.sectionsText === null) {
    problems.push(`${sectionsRel}: missing`);
    return problems;
  }
  const { rows: sections, error } = parseSectionsTable(sources.sectionsText);
  if (error !== null) {
    problems.push(`${sectionsRel}: ${error}`);
    return problems;
  }
  const prefixes = new Set(sections.map((s) => s.prefix));

  for (const rule of sources.ruleFiles) {
    const fm = parseFrontmatter(rule.text);
    if (fm === null) {
      problems.push(`${rule.relPath}: missing or malformed frontmatter`);
      continue;
    }
    const title = fm.data.get("title") ?? "";
    if (title.length === 0) {
      problems.push(`${rule.relPath}: frontmatter title is empty`);
    }
    const impact = fm.data.get("impact") ?? "";
    if (!IMPACT_LEVELS.has(impact)) {
      problems.push(`${rule.relPath}: impact "${impact}" not in {CRITICAL, HIGH, MEDIUM, LOW}`);
    }
    for (const key of fm.data.keys()) {
      if (!RULE_FRONTMATTER_KEYS.has(key)) {
        problems.push(`${rule.relPath}: unknown frontmatter key "${key}"`);
      }
    }
    const h2s = fm.body.split("\n").filter((l) => l.startsWith("## "));
    if (h2s.length !== 1 || h2s[0] !== `## ${title}`) {
      problems.push(`${rule.relPath}: expected exactly one H2 equal to the title`);
    }
    if (extractBlocks(rule.file, RULE_FENCE_LANGS).length === 0) {
      problems.push(`${rule.relPath}: no fenced ts/tsx/jsx block`);
    }
    const referenceLines = fm.body.split("\n").filter((l) => l.trim().startsWith("Reference:"));
    if (referenceLines.length === 0) {
      problems.push(`${rule.relPath}: no Reference: line`);
    } else {
      const paths: string[] = [];
      for (const line of referenceLines) {
        for (const m of line.matchAll(/`([^`]+)`/g)) {
          paths.push(m[1]!.split(/\s+/)[0]!);
        }
      }
      if (paths.length === 0) {
        problems.push(`${rule.relPath}: Reference: line cites no backticked path`);
      }
      for (const cited of paths) {
        if (!fs.existsSync(path.resolve(projectRoot, cited))) {
          problems.push(`${rule.relPath}: Reference path "${cited}" does not resolve in-repo`);
        }
      }
    }
    const prefix = rule.stem.split("-")[0]!;
    if (!prefixes.has(prefix)) {
      problems.push(`${rule.relPath}: filename prefix "${prefix}" matches no _sections.md prefix`);
    }
  }
  return problems;
}

/**
 * Compiles one validated skill's `AGENTS.md`. Deterministic: sections in
 * `_sections.md` order, rules alphabetical by filename stem within section,
 * no timestamps — a second run over unchanged sources is byte-identical.
 * @param sources The loaded skill sources (assumes `validateSkill` returned no problems)
 * @returns The compiled AGENTS.md content
 */
export function compileSkill(sources: SkillSources): string {
  const sections = parseSectionsTable(sources.sectionsText ?? "").rows;
  const metadata = sources.metadata ?? {};
  const out: string[] = [
    `# ${sources.name}`,
    "",
    "Compiled by `vp run skills-build` from `rules/` - never hand-edit; regenerate instead.",
    "",
    String(metadata.abstract ?? ""),
    "",
    `- Version: ${String(metadata.version ?? "")}`,
    `- Organization: ${String(metadata.organization ?? "")}`,
    `- Date: ${String(metadata.date ?? "")}`,
    "",
    "## Impact levels",
    "",
    IMPACT_LEGEND,
    "",
    "## Contents",
    "",
  ];
  const byPrefix = new Map<string, RuleSource[]>();
  for (const rule of sources.ruleFiles) {
    const prefix = rule.stem.split("-")[0]!;
    byPrefix.set(prefix, [...(byPrefix.get(prefix) ?? []), rule]);
  }
  const toc: string[] = [];
  const body: string[] = [];
  sections.forEach((section, sectionIdx) => {
    const sectionNumber = sectionIdx + 1;
    toc.push(`- ${sectionNumber}. ${section.title}`);
    body.push("", `## ${sectionNumber}. ${section.title}`, "");
    const rules = byPrefix.get(section.prefix) ?? [];
    rules.forEach((rule, ruleIdx) => {
      const ruleNumber = `${sectionNumber}.${ruleIdx + 1}`;
      toc.push(`  - ${ruleNumber} ${ruleTitle(rule)} (\`${rule.stem}\`)`);
      const fm = parseFrontmatter(rule.text);
      const bodyLines = (fm?.body ?? "").split("\n");
      const h2Index = bodyLines.findIndex((l) => l.startsWith("## "));
      const ruleBody = bodyLines
        .slice(h2Index + 1)
        .join("\n")
        .trim();
      const impactDescription = fm?.data.get("impactDescription") ?? "";
      const impact = fm?.data.get("impact") ?? "";
      body.push(
        `### ${ruleNumber} ${ruleTitle(rule)}`,
        "",
        `**Impact: ${impact}**${impactDescription ? ` - ${impactDescription}` : ""}`,
        "",
        ruleBody,
        "",
      );
    });
  });
  return `${out.join("\n")}${toc.join("\n")}\n${body.join("\n")}\n`;
}

/**
 * Reads a rule file's frontmatter title (validated to exist).
 * @param rule The rule file
 * @returns The title
 */
function ruleTitle(rule: RuleSource): string {
  return parseFrontmatter(rule.text)?.data.get("title") ?? "";
}

function main(): void {
  try {
    const skillArg = process.argv.slice(2).find((arg) => !arg.startsWith("--"));
    let entries = listSkills().filter((entry) => entry.hasRules);
    if (skillArg !== undefined) {
      entries = entries.filter((entry) => entry.name === skillArg);
      if (entries.length === 0) {
        logger.error(`unknown skill: ${skillArg}`);
        process.exit(1);
      }
    }
    if (entries.length === 0) {
      logger.info("no skills found");
      process.exit(0);
    }

    const problems: string[] = [];
    let compiled = 0;
    let ruleCount = 0;
    for (const entry of entries) {
      const sources = loadSkill(entry);
      const skillProblems = validateSkill(sources);
      if (skillProblems.length > 0) {
        problems.push(...skillProblems);
        continue;
      }
      fs.writeFileSync(path.join(entry.dir, "AGENTS.md"), compileSkill(sources));
      compiled += 1;
      ruleCount += sources.ruleFiles.length;
    }
    if (problems.length > 0) {
      for (const problem of problems) {
        logger.error(problem);
      }
      logger.error(`${problems.length} validation problem(s)`);
      process.exit(1);
    }
    logger.success(`compiled ${compiled} skill(s), ${ruleCount} rule(s)`);
    process.exit(0);
  } catch (error) {
    logger.error("skills-build failed", error as Error);
    process.exit(1);
  }
}

if (process.argv[1] === import.meta.filename) {
  main();
}
